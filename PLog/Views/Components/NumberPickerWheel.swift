    struct Demo: View {
        @State private var weight = 62.5
        @State private var reps = 8
        var body: some View {
            HStack(spacing: 20) {
                NumberPickerWheel(title: "Weight", value: $weight, step: 2.5, range: 0...500, unit: "kg", width: 120)
                NumberPickerWheel(title: "Reps", intValue: $reps, range: 0...100)
            }
            .padding()
        }
    }
    return Demo()
}
